// Package catalog imports kingfisher's detection formats that pleno-dlp's
// native detectors do not match (docs/kingfisher-parity.md, epic #817).
//
// Each rule either extends an existing provider DetectorType through
// detectors.RegisterFormats (format variants, context-anchored legacy
// shapes, sibling credential kinds), or belongs to a catalog host: a
// detection-only DetectorType for a provider with no native detector,
// classified in docs/verify-coverage.md. Catalog findings are never
// verified (ExtraData["verification"]="not-attempted"); paired and signed
// verification for the validated rules is tracked in #898.
//
// catalog_gen.go is generated by scripts/kingfisher-catalog.py; edit the
// generator, not the table.
package catalog

import (
	"context"
	"sort"
	"strings"

	"github.com/plenoai/pleno-dlp/pkg/detectors"
)

type rule struct {
	ID         string
	Type       detectors.DetectorType
	Validation string // kingfisher's validation type ("-" = detection only)
	Group      int
	MinEntropy float64
	Keywords   []string
	Pattern    string
	Path       string // RE2 the source path must match ("" = any)
}

func (r rule) format() *detectors.Format {
	return &detectors.Format{
		ID: r.ID, Keywords: r.Keywords, Pattern: r.Pattern,
		Group: r.Group, MinEntropy: r.MinEntropy, Path: r.Path,
	}
}

// Host is the detection-only scanner for a catalog host type.
type Host struct {
	t        detectors.DetectorType
	formats  []*detectors.Format
	keywords []string
}

func (h *Host) Type() detectors.DetectorType { return h.t }

func (h *Host) Keywords() []string { return h.keywords }

func (h *Host) FromData(_ context.Context, _ bool, data []byte) ([]detectors.Result, error) {
	return detectors.SafeResults(detectors.MatchFormats(h.t, h.formats, data, nil)), nil
}

// Formats returns the host's formats (for tests).
func (h *Host) Formats() []*detectors.Format { return h.formats }

// Hosts returns the catalog host scanners, sorted by type.
func Hosts() []*Host { return hostScanners }

// Extensions returns the formats attached to existing provider types.
func Extensions() map[detectors.DetectorType][]*detectors.Format { return extensions }

var (
	hostScanners []*Host
	extensions   = map[detectors.DetectorType][]*detectors.Format{}
)

// build groups the rules into host scanners and provider extensions.
func build() {
	isHost := map[detectors.DetectorType]*Host{}
	for _, t := range hosts {
		h := &Host{t: t}
		isHost[t] = h
		hostScanners = append(hostScanners, h)
	}
	for _, r := range rules {
		f := r.format()
		// Path-constrained rules need the source path, which only the
		// engine's format hook supplies, so they stay extensions even on
		// host types.
		if h, ok := isHost[r.Type]; ok && r.Path == "" {
			h.formats = append(h.formats, f)
			continue
		}
		extensions[r.Type] = append(extensions[r.Type], f)
	}
	for _, h := range hostScanners {
		seen := map[string]bool{}
		for _, f := range append(append([]*detectors.Format(nil), h.formats...), extensions[h.t]...) {
			for _, kw := range f.Keywords {
				if k := strings.ToLower(kw); k != "" && !seen[k] {
					seen[k] = true
					h.keywords = append(h.keywords, kw)
				}
			}
		}
		sort.Strings(h.keywords)
	}
}
