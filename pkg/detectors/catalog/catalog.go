// Package catalog imports kingfisher's detection formats that pleno-dlp's
// native detectors do not match (docs/kingfisher-parity.md, epic #817).
//
// Each rule either extends an existing provider DetectorType through
// detectors.RegisterFormats (format variants, context-anchored legacy
// shapes, sibling credential kinds), or belongs to a catalog host: a
// DetectorType for a provider with no native detector. Every rule
// kingfisher validates carries a check (checks.go, issue #934): routed to
// the provider's verifier, a declarative request, or a signed scheme,
// with paired credentials resolved from the surrounding text the way
// kingfisher's depends_on does. Hosts with checks are Verifiers; the
// rest are classified in docs/verify-coverage.md.
//
// catalog_gen.go is generated by scripts/kingfisher-catalog.py; edit the
// generator, not the table.
package catalog

import (
	"context"
	"fmt"
	"sort"
	"strings"

	"github.com/plenoai/pleno-dlp/pkg/detectors"
)

type rule struct {
	ID         string
	Type       detectors.DetectorType
	Validation string // kingfisher's validation type ("-" = detection only)
	Group      int
	MinEntropy float64
	Keywords   []string
	Pattern    string
	Path       string // RE2 the source path must match ("" = any)
}

func (r rule) format() *detectors.Format {
	return &detectors.Format{
		ID: r.ID, Keywords: r.Keywords, Pattern: r.Pattern,
		Group: r.Group, MinEntropy: r.MinEntropy, Path: r.Path,
	}
}

// Host is the detection-only scanner for a catalog host type.
type Host struct {
	t        detectors.DetectorType
	formats  []*detectors.Format
	keywords []string
}

func (h *Host) Type() detectors.DetectorType { return h.t }

func (h *Host) Keywords() []string { return h.keywords }

func (h *Host) FromData(ctx context.Context, verify bool, data []byte) ([]detectors.Result, error) {
	res := detectors.MatchFormats(h.t, h.formats, data, nil)
	if verify {
		detectors.VerifyFormatResults(ctx, h.formats, data, res)
	}
	return detectors.SafeResults(res), nil
}

// verifyingHost is a Host with at least one kingfisher-validated rule.
// FromData verifies with the surrounding text (paired credentials); a
// bare Verify(secret) picks the rule by prefix and reports a missing
// partner as indeterminate.
type verifyingHost struct {
	*Host
	ids []string
}

func (h *verifyingHost) Verify(ctx context.Context, secret string) (bool, error) {
	id := ""
	for _, c := range h.ids {
		if p := checks[c].prefix; p != "" && strings.HasPrefix(secret, p) && len(p) > len(checks[id].prefixOr()) {
			id = c
		}
	}
	if id == "" {
		if len(h.ids) != 1 {
			return false, fmt.Errorf("%s verify: cannot tell which credential kind this is without its context", h.t)
		}
		id = h.ids[0]
	}
	return checks[id].verify(ctx, h.t, id, secret, nil)
}

func (h *verifyingHost) MaxVerificationAssurance() detectors.VerificationAssurance {
	best := detectors.AssuranceUnknown
	for _, id := range h.ids {
		if a := checks[id].assurance; a > best {
			best = a
		}
	}
	return best
}

// VerificationCacheUsesFullInput is true when any check pairs a partner
// credential from the surrounding text, so Raw alone does not determine
// the verdict.
func (h *verifyingHost) VerificationCacheUsesFullInput() bool {
	for _, id := range h.ids {
		if len(checks[id].partners) > 0 {
			return true
		}
	}
	return false
}

// Formats returns the host's formats (for tests).
func (h *Host) Formats() []*detectors.Format { return h.formats }

// Hosts returns the catalog host scanners, sorted by type.
func Hosts() []*Host { return hostScanners }

// detector returns the registrable form of h: a Verifier when any of its
// rules carries a check.
func (h *Host) detector() detectors.Detector {
	var ids []string
	for _, f := range append(append([]*detectors.Format(nil), h.formats...), extensions[h.t]...) {
		if _, ok := checks[f.ID]; ok {
			ids = append(ids, f.ID)
		}
	}
	if len(ids) == 0 {
		return h
	}
	sort.Strings(ids)
	return &verifyingHost{Host: h, ids: ids}
}

// Verifies reports whether h is registered as a Verifier.
func (h *Host) Verifies() bool {
	_, ok := h.detector().(detectors.Verifier)
	return ok
}

// Extensions returns the formats attached to existing provider types.
func Extensions() map[detectors.DetectorType][]*detectors.Format { return extensions }

var (
	hostScanners []*Host
	extensions   = map[detectors.DetectorType][]*detectors.Format{}
	ruleType     = map[string]detectors.DetectorType{}
)

// build groups the rules into host scanners and provider extensions.
func build() {
	isHost := map[detectors.DetectorType]*Host{}
	for _, t := range hosts {
		h := &Host{t: t}
		isHost[t] = h
		hostScanners = append(hostScanners, h)
	}
	for _, r := range append(append([]rule(nil), rules...), extraRules...) {
		ruleType[r.ID] = r.Type
		f := r.format()
		f.Prefilter = prefilters[r.ID]
		// Path-constrained rules need the source path, which only the
		// engine's format hook supplies, so they stay extensions even on
		// host types.
		if h, ok := isHost[r.Type]; ok && r.Path == "" {
			h.formats = append(h.formats, f)
			continue
		}
		extensions[r.Type] = append(extensions[r.Type], f)
	}
	for _, h := range hostScanners {
		seen := map[string]bool{}
		for _, f := range append(append([]*detectors.Format(nil), h.formats...), extensions[h.t]...) {
			for _, kw := range f.Keywords {
				if k := strings.ToLower(kw); k != "" && !seen[k] {
					seen[k] = true
					h.keywords = append(h.keywords, kw)
				}
			}
		}
		sort.Strings(h.keywords)
	}
	attach()
}
