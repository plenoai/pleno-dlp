// Package vercel detects Vercel API access tokens. Tokens are 24-char
// alphanumeric — a generic shape that hits constantly in real codebases —
// so we require a "vercel" / "VERCEL_TOKEN" co-occurrence within 256 bytes
// of the candidate before surfacing it. Verify hits /v2/user with Bearer.
package vercel

import (
	"context"
	"net/http"
	"regexp"
	"strings"
	"time"

	"github.com/plenoai/pleno-dlp/pkg/detectors"
)

var apiBase = "https://api.vercel.com"

var httpClient = &http.Client{Timeout: 10 * time.Second}

// 24 alphanumeric. No prefix to anchor on, so the keyword gate carries the
// false-positive load.
var tokenRe = regexp.MustCompile(`\b([A-Za-z0-9]{24})\b`)

var contextKeywords = []string{"vercel", "vercel_token"}

type Scanner struct{}

func (Scanner) Type() detectors.DetectorType { return detectors.Vercel }

// Keywords must include "vercel" — without it the engine would have no
// gate at all and we'd evaluate the 24-char regex against every chunk.
func (Scanner) Keywords() []string { return []string{"vercel"} }

func (s Scanner) FromData(ctx context.Context, verify bool, data []byte) ([]detectors.Result, error) {
	hits := tokenRe.FindAllSubmatchIndex(data, -1)
	if len(hits) == 0 {
		return nil, nil
	}
	lower := strings.ToLower(string(data))
	out := make([]detectors.Result, 0, len(hits))
	seen := map[string]struct{}{}
	for _, h := range hits {
		token := string(data[h[2]:h[3]])
		if _, dup := seen[token]; dup {
			continue
		}
		// Co-occurrence with a "vercel" keyword is mandatory — 24-char
		// alphanumerics are common (commit shas, nonces, k8s names).
		if !nearKeyword(lower, h[2], h[3]) {
			continue
		}
		seen[token] = struct{}{}
		res := detectors.Result{
			DetectorType: detectors.Vercel,
			Raw:          []byte(token),
			Redacted:     redact(token),
		}
		if verify {
			v, err := s.Verify(ctx, token)
			res.Verified = v
			res.VerificationErr = err
		}
		out = append(out, res)
	}
	return out, nil
}

func nearKeyword(lower string, start, end int) bool {
	const radius = 256
	from := start - radius
	if from < 0 {
		from = 0
	}
	to := end + radius
	if to > len(lower) {
		to = len(lower)
	}
	window := lower[from:to]
	for _, kw := range contextKeywords {
		if strings.Contains(window, kw) {
			return true
		}
	}
	return false
}

func (Scanner) Verify(ctx context.Context, secret string) (bool, error) {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, apiBase+"/v2/user", nil)
	if err != nil {
		return false, err
	}
	req.Header.Set("Authorization", "Bearer "+secret)

	resp, err := httpClient.Do(req)
	if err != nil {
		return false, err
	}
	defer resp.Body.Close()
	switch resp.StatusCode {
	case http.StatusOK:
		return true, nil
	case http.StatusUnauthorized, http.StatusForbidden, http.StatusTooManyRequests:
		return false, nil
	default:
		return false, nil
	}
}

func redact(t string) string {
	if len(t) <= 6 {
		return t
	}
	return t[:6] + "..."
}

func init() {
	detectors.Register(Scanner{})
}
