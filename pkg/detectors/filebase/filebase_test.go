package filebase

import (
	"context"
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"

	"github.com/plenoai/pleno-dlp/pkg/detectors"
)

const (
	dummyKey    = "ABCDEFGHIJKLMNOPQRST"
	dummySecret = "abcdefghijklmnopqrstuvwxyz0123456789ABCDEF"
)

func TestType(t *testing.T) {
	if (Scanner{}).Type() != detectors.Filebase {
		t.Fatal("type mismatch")
	}
}

func TestKeywords(t *testing.T) {
	if got := (Scanner{}).Keywords(); len(got) == 0 {
		t.Fatal("keywords empty")
	}
}

func TestFromData_Found(t *testing.T) {
	body := []byte("FILEBASE_ACCESS_KEY=" + dummyKey + " FILEBASE_SECRET_KEY=" + dummySecret)
	res, _ := Scanner{}.FromData(context.Background(), false, body)
	if len(res) == 0 {
		t.Fatal("expected >=1")
	}
	if !strings.Contains(string(res[0].RawV2), dummySecret) {
		t.Fatalf("rawv2 missing secret: %s", string(res[0].RawV2))
	}
}

func TestFromData_NoKeyword(t *testing.T) {
	body := []byte("UNRELATED_ONE=" + dummyKey + " UNRELATED_TWO=" + dummySecret)
	res, _ := Scanner{}.FromData(context.Background(), false, body)
	if len(res) != 0 {
		t.Fatalf("expected 0, got %d", len(res))
	}
}

func TestVerify_Disabled_Default(t *testing.T) {
	v, _ := Scanner{}.Verify(context.Background(), dummyKey+":"+dummySecret)
	if v {
		t.Fatal("expected verified=false default")
	}
}

func TestVerify_OK(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if !strings.Contains(r.Header.Get("Authorization"), dummyKey) {
			t.Errorf("auth missing key id")
		}
		w.WriteHeader(http.StatusOK)
	}))
	defer srv.Close()
	old := apiBase
	apiBase = srv.URL
	defer func() { apiBase = old }()
	v, err := Scanner{}.Verify(context.Background(), dummyKey+":"+dummySecret)
	if err != nil || !v {
		t.Fatalf("err=%v v=%v", err, v)
	}
}

